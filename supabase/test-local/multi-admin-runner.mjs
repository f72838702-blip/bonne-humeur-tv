let pass = 0, fail = 0;
const failures = [];
const ok = (id, label) => { pass++; console.log(`  PASS  ${id} — ${label}`); };
const no = (id, label, d = "") => { fail++; failures.push(id); console.log(`  FAIL  ${id} — ${label}${d ? " → " + d : ""}`); };
async function expect(id, label, fn) {
  try { if (await fn()) ok(id, label); else no(id, label); }
  catch (e) { no(id, label, e.message); }
}
/** Attend une EXCEPTION SQL = la base refuse l'action (règle sécurité). */
async function expectRefused(id, label, fn) {
  try { await fn(); no(id, label, "RÉUSSI (aurait dû être refusé par la base)"); }
  catch { ok(id, label); }
}
/** boolean : true si l'action a été REFUSÉE par la base (usage en expression). */
async function refused(fn) {
  try { await fn(); return false; } catch { return true; }
}
const NUM = (r) => Number(r.rows[0]?.n ?? 0);
const VAL = (r, col = "v") => r.rows[0]?.[col];

let c = new Client({ host: "127.0.0.1", port: 5433, user: "postgres", database: DB });

/** Requête EN SESSION AUTORISÉE (rôle + JWT simulé), transaction propre. */
async function as(role, uid, sql, params) {
  await c.query("begin");
  try {
    await c.query(`set local role ${role}`);
    if (uid) await c.query("select set_config('request.jwt.claim.sub', $1, true)", [uid]);
    const r = await c.query(sql, params ?? []);
    await c.query("commit");
    return r;
  } catch (e) {
    await c.query("rollback");
    throw e;
  }
}

/** Souverain de la base (migrations / SQL Editor = « postgres »). */
async function root(sql, params) {
  return c.query(sql, params);
}

async function applyChain() {
  let cronStubReady = false;
  const ensureCronStub = async () => {
    if (cronStubReady) return;
    cronStubReady = true;
    await c.query(`create schema if not exists cron;
      create table if not exists cron.job (
        jobid bigint generated by default as identity primary key,
        jobname text, schedule text, command text, active boolean default true
      );
      create or replace function cron.schedule(p_schedule text, p_command text)
        returns bigint as $$ select 1 $$ language sql;
      create or replace function cron.schedule(p_name text, p_schedule text, p_command text)
        returns bigint as $$
          insert into cron.job (jobname, schedule, command) values (p_name, p_schedule, p_command)
          returning jobid
        $$ language sql;`);
  };
  for (const f of FILES) {
    try {
      await c.query(readFile(f));
      console.log(`  ok    ${f}`);
    } catch (e) {
      if (/pg_cron/i.test(e.message)) {
        await ensureCronStub();
        await c.query(readFile(f).replace(/create extension if not exists pg_cron;\s*/gi, ""));
        console.log(`  ok    ${f}    (sans pg_cron — émulation locale)`);
      } else {
        console.log(`  ÉCHEC ${f} → ${e.message}`);
        await c.end();
        process.exit(1);
      }
    }
  }
}

