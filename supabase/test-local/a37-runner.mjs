const database = process.argv[2] ?? "bhtv_a37";

let pass = 0, fail = 0;
const failures = [];
function report(id, label, ok, detail = "") {
  if (ok) { pass++; console.log(`  PASS  ${id} — ${label}`); }
  else { fail++; failures.push(id); console.log(`  FAIL  ${id} — ${label}${detail ? " → " + detail : ""}`); }
}

async function q(client, user, text, params = []) {
  await client.query(`set role ${user}`);
  try { return await client.query(text, params); }
  finally { await client.query(`reset role`); }
}

const c = new Client({ host: HOST, port: PORT, user: "postgres", database });
