// Utilisateurs de test : DEUX admins distincts + un éditeur (isolation entre
// comptes AUTHERISÉS exigée par la direction §5).
const U_ADMIN1 = "11111111-1111-1111-1111-111111111101";
const U_ADMIN2 = "11111111-1111-1111-1111-111111111102";
const U_EDITOR = "11111111-1111-1111-1111-111111111103";

let pass = 0, fail = 0;
const failures = [];
const ok = (id, label) => { pass++; console.log(`  PASS  ${id} — ${label}`); };
const no = (id, label, d = "") => { fail++; failures.push(id); console.log(`  FAIL  ${id} — ${label}${d ? " → " + d : ""}`); };
async function expect(id, label, fn) {
  try { if (await fn()) ok(id, label); else no(id, label); }
  catch (e) { no(id, label, e.message); }
}
const eq = (got, want) => JSON.stringify(got) === JSON.stringify(want);
// count(*) BIGINT arriva en STRING depuis pg — coercer systématiquement.
const NUM = (r) => Number(SCALAR(r, "n"));

const c = new Client({ host: "127.0.0.1", port: 5433, user: "postgres", database: process.argv[3] ?? "bhtv_mem" });

async function as(role, uid, sql, params) {
  await c.query("begin");
  try {
    await c.query(`set local role ${role}`);
    if (uid) await c.query("select set_config('request.jwt.claim.sub', $1, true)", [uid]);
    const r = await c.query(sql, params ?? []);
    await c.query("commit");
    return r;
  } catch (e) {
    await c.query("rollback");
    throw e;
  }
}
const SCALAR = (rows, col) => Object.values(rows.rows[0] ?? {})[0];

async function main() {
  await c.connect();

  if (process.argv[2] === "fresh") {
    console.log("=== Application de la chaîne complète 0001 → 0033 (base vierge) ===");
    // Stub pg_cron local (PostgreSQL portable sans l'extension) — migrations
    // JAMAIS modifiées : 0030 est appliquée sans sa ligne create extension et
    // schedulée via un cron.schedule fictif (la purge est testée hors harnais).
    let cronStubReady = false;
    const ensureCronStub = async () => {
      if (cronStubReady) return;
      await c.query(`create schema if not exists cron;
        create table if not exists cron.job (
          jobid bigint generated by default as identity primary key,
          jobname text, schedule text, command text, active boolean default true
        );
        create or replace function cron.schedule(p_schedule text, p_command text)
          returns bigint as $$ select 1 $$ language sql;
        create or replace function cron.schedule(p_name text, p_schedule text, p_command text)
          returns bigint as $$
            insert into cron.job (jobname, schedule, command) values (p_name, p_schedule, p_command)
            returning jobid
          $$ language sql;
        create or replace function cron.unschedule(p_name text)
          returns boolean as $$
            declare n bigint;
            begin
              delete from cron.job where jobname = p_name;
              return n > 0;
            end
          $$ language plpgsql;`);
      cronStubReady = true;
    };
    for (const f of FILES) {
      try {
        await c.query(readFile(f));
        console.log(`  ok    ${f}`);
      } catch (e) {
        if (/pg_cron/.test(e.message)) {
          try {
            await ensureCronStub();
            await c.query(
              readFile(f).replace(/create extension if not exists pg_cron;\s*/gi, "")
            );
            console.log(`  ok    ${f}    (sans pg_cron — émulation locale)`);
          } catch (e2) {
            console.log(`  ÉCHEC ${f} → ${e2.message}`);
            process.exitCode = 1;
            await c.end();
            return;
          }
        } else {
          console.log(`  ÉCHEC ${f} → ${e.message}`);
          process.exitCode = 1;
          await c.end();
          return;
        }
      }
    }
  } else {
    // Vérification minimale : 0033 est-elle en place ?
    const t = await c.query(
      "select to_regclass('public.ai_conversations') is not null as t"
    );
    if (!t.rows[0].t) {
      console.log("0033 absent — relancez avec `fresh`");
      process.exitCode = 1;
      await c.end();
      return;
    }
  }

  // Comptes de test : insertion dans auth.users (émulé) → le trigger 0003 crée
  // les profiles ; le rôle est ensuite fixé (admin pour admin1/admin2, editor).
  for (const [uid, email, role] of [
    [U_ADMIN1, "admin1@bhtv.test", "admin"],
    [U_ADMIN2, "admin2@bhtv.test", "admin"],
    [U_EDITOR, "editor@bhtv.test", "editor"],
  ]) {
    await c.query(
      `insert into auth.users (id, email, raw_user_meta_data) values ($1, $2, '{"full_name":"Compte Test"}'::jsonb)
       on conflict (id) do nothing`,
      [uid, email]
    );
    await c.query(
      `update public.profiles set role = $2 where id = $1 and role <> $2`,
      [uid, role]
    );
  }

  console.log("\n=== TESTS MÉMOIRE ADMIN (0033) ===");

  // MEM1 — création de conversation par admin1 + titre dérivé
  const convId = SCALAR(
    await as("authenticated", U_ADMIN1,
      "insert into public.ai_conversations (owner_user_id, title) values (auth.uid(), 'Campagne décembre') returning id"),
    "id"
  );
  await expect("MEM1", "création conversation par son propriétaire (RLS)",
    () => typeof convId === "string" && convId.length === 36);

  // MEM2 — l'ADMIN2 ne voit PAS la conversation de admin1 (isolation stricte)
  await expect("MEM2", "isolation : admin2 ne lit pas la conversation de admin1",
    async () => eq(
      NUM(await as("authenticated", U_ADMIN2,
        "select count(*) n from public.ai_conversations where id = $1", [convId])), 0));

  // MEM2b — l'ÉDITEUR ne la voit pas non plus
  await expect("MEM2b", "isolation : éditeur ne lit pas la conversation d'admin1",
    async () => eq(
      NUM(await as("authenticated", U_EDITOR,
        "select count(*) n from public.ai_conversations where id = $1", [convId])), 0));

  // MEM3 — messages liés + cascade au delete
  await as("authenticated", U_ADMIN1,
    "insert into public.ai_messages (conversation_id, role, content) values ($1, 'user', 'Décision : campagne décembre à 3 visuels.')", [convId]);
  await as("authenticated", U_ADMIN1,
    "insert into public.ai_messages (conversation_id, role, content) values ($1, 'assistant', 'Compris — 3 visuels prévus.')", [convId]);

  await expect("MEM3", "messages lisibles par le propriétaire, ordre chronologique",
    async () => eq(
      (await as("authenticated", U_ADMIN1,
        "select role from public.ai_messages m where m.conversation_id = $1 order by m.created_at", [convId])).rows.map(r => r.role),
      ["user", "assistant"]));

  // MEM4 — les autres comptes ne lisent PAS les messages (RLS via EXISTS)
  await expect("MEM4", "messages invisibles à admin2 (RLS conversations)",
    async () => eq(
      NUM(await as("authenticated", U_ADMIN2,
        "select count(*) n from public.ai_messages")), 0));

  // MEM5 — insertion de message dans une conversation D'AUTRUI refuse (RLS)
  await expect("MEM5", "écrire un message dans la conversation d'autrui est refusé",
    async () => {
      try {
        await as("authenticated", U_ADMIN2,
          "insert into public.ai_messages (conversation_id, role, content) values ($1, 'user', 'pirate')", [convId]);
        return false;
      } catch {
        return true;
      }
    });

  // MEM6 — renommage par le propriétaire
  await as("authenticated", U_ADMIN1,
    "update public.ai_conversations set title = 'Campagne DÉCEMBRE' where id = $1", [convId]);
  await expect("MEM6", "renommage propriétaire ok",
    async () => eq(
      SCALAR(await as("authenticated", U_ADMIN1, "select title from public.ai_conversations where id = $1", [convId]), "title"),
      "Campagne DÉCEMBRE"));

  // MEM7 — anonyme : ZÉRO accès (tables privées : grants revoked à anon)
  await expect("MEM7", "anon : lecture REFUSÉE (grant revoked, RLS)",
    async () => {
      try { await as("anon", null, "select count(*) n from public.ai_conversations"); return false; }
      catch { return true; }
    });

  // MEM8 — TRUNCATE refusé au staff (durcissement 0031)
  await expect("MEM8", "authenticated : TRUNCATE refusé (grant revoke)",
    async () => {
      try {
        await as("authenticated", U_ADMIN1, "truncate public.ai_conversations");
        return false;
      } catch {
        return true;
      }
    });

  // MEM9 — mémoire contextuelle isolée par compte
  await as("authenticated", U_ADMIN1,
    "insert into public.ai_memories (user_id, content) values (auth.uid(), 'Décision : régie en 1 page ultra simple ; préférences : ton chaleureux.')");
  await expect("MEM9", "admin1 lit SA mémoire",
    async () => String(SCALAR(await as("authenticated", U_ADMIN1, "select content from public.ai_memories where user_id = $1", [U_ADMIN1]), "content")).includes("régie en 1 page"));
  await expect("MEM9b", "admin2 NE lit PAS la mémoire d'admin1",
    async () => eq(
      NUM(await as("authenticated", U_ADMIN2, "select count(*) n from public.ai_memories")), 0));

  // MEM9c — upsert mémoire : une seule ligne par utilisateur
  await as("authenticated", U_ADMIN1,
    "update public.ai_memories set content = 'Décision A ; préférence B.' where user_id = auth.uid()");
  await expect("MEM9c", "mémoire mise à jour (pas de 2e ligne)",
    async () => eq(
      NUM(await as("authenticated", U_ADMIN1, "select count(*) n from public.ai_memories where user_id = $1", [U_ADMIN1])), 1));

  // MEM10 — suppression EFFECTIVE : cascade messages
  let conv2;
  try {
    await c.query("begin");
    await c.query("set local role authenticated");
    await c.query("select set_config('request.jwt.claim.sub', $1, true)", [U_ADMIN1]);
    const r = await c.query(
      "insert into public.ai_conversations (owner_user_id, title) values (auth.uid(), 'A supprimer') returning id");
    conv2 = r.rows[0].id;
    await c.query(
      "insert into public.ai_messages (conversation_id, role, content) values ($1, 'user', 'x')", [conv2]);
    await c.query("commit");
  } catch { await c.query("rollback"); }

  await as("authenticated", U_ADMIN1, "delete from public.ai_conversations where id = $1", [conv2]);
  await expect("MEM10", "suppression effective : messages effacés en cascade",
    async () => typeof conv2 === "string" && conv2.length === 36 &&
      NUM(await c.query("select count(*) n from public.ai_messages where conversation_id = $1", [conv2])) === 0);

  // MEM11 — audit : écrit sans CONTENU (aucune fuite de contenu dans audit_logs)
  await expect("MEM11", "audit_logs ne contient pas le contenu des messages",
    async () => NUM(await c.query("select count(*) n from public.audit_logs where entity = 'ai_messages' and action in ('insert','delete')")) > 0);
  const auditCols = (await c.query("select column_name from information_schema.columns where table_name = 'audit_logs'")).rows.map(r => r.column_name);
  await expect("MEM11b", "audit_logs sans colonne payload (pas de contenu)",
    () => !auditCols.some(k => /content|payload|data/i.test(k)));

  // MEM12 — contrainte de bornes SQL : titre > 200 refusé
  await expect("MEM12", "titre > 200 caractères refusé (contrainte SQL)",
    async () => {
      try {
        await as("authenticated", U_ADMIN1,
          "insert into public.ai_conversations (owner_user_id, title) values (auth.uid(), $1)", ["t".repeat(201)]);
        return false;
      } catch { return true; }
    });

  // MEM13 — AUCUNE ligne ai_* lisible par le PUBLIC search (0 SECURITY DEFINER lit ces tables)
  await expect("MEM13", "search_published ne cite aucune table ai_*",
    async () => eq(
      NUM(await c.query("select count(*) n from information_schema.routine_column_usage where routine_name = 'search_published' and table_name like 'ai_%'")), 0));

  console.log(`\n=== RÉSULTAT : ${pass} PASS / ${fail} FAIL ===`);
  if (failures.length > 0) { process.exitCode = 1; }
  await c.end();
}

main().catch((e) => { console.error(e); process.exit(1); });
